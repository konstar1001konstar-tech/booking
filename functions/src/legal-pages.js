// Страницы /privacy (политика платформы) и /terms-masters (условия для
// мастеров с поручением на обработку). Рендерятся функцией: реквизиты
// владельца берутся из OWNER_FIO / OWNER_INN / OWNER_EMAIL. Пустые
// реквизиты просто не выводятся.

const { escapeHtml } = require('./lib/html');

function ownerLine(owner) {
  const parts = [];
  if (owner.fio) parts.push(owner.fio + ', плательщик налога на профессиональный доход (самозанятый)');
  else parts.push('владелец сервиса БьютиЛинк, плательщик налога на профессиональный доход (самозанятый)');
  if (owner.inn) parts.push('ИНН ' + owner.inn);
  return parts.join(', ');
}

function contactLine(owner, bot) {
  if (owner.email) return 'по электронной почте ' + owner.email;
  if (bot) return 'через Telegram-бота @' + bot;
  return 'через контакты, указанные внизу главной страницы';
}

function page(title, base, sections) {
  const body = sections.map(([h, paras]) => {
    const ps = (Array.isArray(paras) ? paras : [paras])
      .map((t) => '<p class="mt-2 text-[15px] leading-relaxed text-muted">' + escapeHtml(t) + '</p>').join('\n');
    return '<section class="mt-7"><h2 class="text-lg font-semibold text-ink">' + escapeHtml(h) + '</h2>\n' + ps + '</section>';
  }).join('\n');
  return '<!DOCTYPE html>\n<html lang="ru" class="theme-plum">\n<head>\n<meta charset="utf-8">\n'
    + '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
    + '<meta http-equiv="Content-Security-Policy" content="default-src \'self\'; script-src \'none\'; style-src \'self\'; img-src \'self\' data:; font-src \'self\'; object-src \'none\'; base-uri \'self\'; form-action \'none\'">\n'
    + '<meta name="robots" content="index">\n'
    + '<title>' + escapeHtml(title) + ' · БьютиЛинк</title>\n'
    + '<link rel="icon" href="/favicon.svg" type="image/svg+xml">\n'
    + '<link rel="stylesheet" href="/styles.css">\n</head>\n'
    + '<body class="bg-milk text-ink antialiased">\n'
    + '<main class="mx-auto max-w-2xl px-6 pb-16 pt-10">\n'
    + '<a href="/" class="wordmark text-[24px]"><b>Бьюти</b><i>Линк</i></a>\n'
    + '<h1 class="display mt-6 text-[30px] font-semibold leading-tight text-ink">' + escapeHtml(title) + '</h1>\n'
    + body + '\n'
    + '<p class="mt-10 text-xs text-muted"><a class="text-tg underline" href="/privacy">Политика конфиденциальности</a> · '
    + '<a class="text-tg underline" href="/terms-masters">Условия для мастеров</a> · <a class="text-tg underline" href="/">На главную</a></p>\n'
    + '</main>\n</body>\n</html>\n';
}

